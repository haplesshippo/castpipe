func TestPhysicalLines(t *testing.T) {
	for _, lines := range []int{0, 1, 800, 801, 1000, 1001} {
		for _, newline := range []string{"\n", "\r\n"} {
			for _, terminated := range []bool{false, true} {
				t.Run(fmt.Sprintf("%d/%q/terminated=%t", lines, newline, terminated), func(t *testing.T) {
					data := strings.Repeat("// comment"+newline, lines)
					if !terminated {
						data = strings.TrimSuffix(data, newline)
					}
					if got := physicalLines([]byte(data)); got != lines {
						t.Fatalf("got %d, want %d", got, lines)
					}
				})
			}
		}
	}
	if got := physicalLines([]byte("\n\r\n// comment\n")); got != 3 {
		t.Fatalf("blank and comment lines: got %d, want 3", got)
	}
}

// Exercise the actual developer/CI entry point in a fresh directory without
// Git metadata: new files must be found, and warnings must still exit zero.
func TestFileLengthGoTest(t *testing.T) {
	root := t.TempDir()
	write := func(path, data string) {
		t.Helper()
		path = filepath.Join(root, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(data), 0644); err != nil {
			t.Fatal(err)
		}
	}
	policy, err := os.ReadFile("loc_policy_test.go")
	if err != nil {
		t.Fatal(err)
	}
	write("loc_policy_test.go", string(policy))
	write("go.mod", "module locfixture\n\ngo 1.24\n")
	code := func(lines int) string { return "package main\n" + strings.Repeat("\n", lines-1) }
	write("new file.go", code(800))
	write("testdata/gen.go", strings.ReplaceAll(code(801), "\n", "\r\n"))
	write("new_test.go", strings.TrimSuffix(code(1000), "\n")+"// final line")
	write("build/tool.go", code(801))
	write("dist/tool.go", code(801))
	write(".github/workflows/ci.yml", strings.Repeat("# command config\n", 801))
	write(".no-mistakes.yaml", strings.Repeat("# command config\n", 1000))
	for _, path := range []string{"README.md", "testdata/payload.json", "testdata/mdns-replies.bin", "go.sum", "castpipe"} {
		write(path, strings.Repeat("content\n", 1001))
	}
	for _, path := range []string{"vendor/lib/file.go", ".git/scratch.go"} {
		write(path, code(1001))
	}
	write("generated.go", "// Code generated by fixture. DO NOT EDIT.\n"+code(1001))
	run := func() (string, error) {
		t.Helper()
		cmd := exec.Command("go", "test", "-v", "-count=1", "./...")
		cmd.Dir = root
		cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=")
		out, err := cmd.CombinedOutput()
		return string(out), err
	}
	out, err := run()
	if err != nil {
		t.Fatalf("warnings must pass: %v\n%s", err, out)
	}
	for _, path := range []string{"testdata/gen.go", "new_test.go", "build/tool.go", "dist/tool.go", ".github/workflows/ci.yml", ".no-mistakes.yaml"} {
		if !strings.Contains(out, "warning: "+path+":") {
			t.Errorf("missing warning for %s:\n%s", path, out)
		}
	}
	if strings.Contains(out, "warning: new file.go:") {
		t.Fatalf("800 lines must not warn:\n%s", out)
	}
	for _, path := range []string{"new file.go", "testdata/gen.go", ".github/workflows/ci.yml"} {
		if strings.HasSuffix(path, ".go") {
			write(path, strings.TrimSuffix(code(1001), "\n")+"// final line")
		} else {
			write(path, strings.Repeat("# command config\r\n", 1001))
		}
	}
	out, err = run()
	if err == nil {
		t.Fatalf("1001 lines must fail:\n%s", out)
	}
	for _, path := range []string{"new file.go", "testdata/gen.go", ".github/workflows/ci.yml"} {
		if !strings.Contains(out, path+": 1001 lines exceeds hard limit 1000") {
			t.Errorf("missing hard failure for %s:\n%s", path, out)
		}
	}
}
